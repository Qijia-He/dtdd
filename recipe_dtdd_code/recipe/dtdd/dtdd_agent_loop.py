"""DTDD tool agent loop: divergence-triggered teacher takeover.

``run()`` is a pinned copy of ``ToolAgentLoop.run`` (``verl/experimental/
agent_loop/tool_agent_loop.py`` at YoungZ365/SOD@110c4b8) extended with:

* a per-episode epsilon-greedy trigger draw (divergence vs. random turn);
* per-turn teacher scoring of the freshly generated student turn,
  ``d_k = mean |student_logprob - teacher_logprob|`` -- the same divergence
  ``compute_stepwise_opd_weights`` uses in the trainer;
* teacher takeover: the remaining turns are generated by the frozen teacher
  vLLM pool. ``rewind`` discards the divergent turn and lets the teacher
  regenerate it from ``h_{k-1}``; ``inherit`` keeps the divergent turn and
  the teacher continues after it;
* a per-token origin mask emitted through the otherwise dormant
  ``teacher_kl_mask`` plumbing (1 = student-origin assistant token,
  0 = teacher or tool token);
* telemetry via ``extra_info``. ``AgentLoopMetrics`` is a fixed pydantic
  model and would drop unknown keys.

The loop is registered over the stock ``tool_agent`` name by
``recipe/dtdd/config/agent_loop.yaml``. When ``dtdd.enable`` is false, or the
sample is a validation sample (``kwargs["dtdd_validate"]``), the behaviour is
identical to the stock loop and no origin mask is emitted.

Environment knobs (read here; the teacher server documents its own):

``DTDD_TEACHER_VOCAB_CAP``
    Highest token id + 1 the teacher may emit when its vocabulary is larger
    than the student's (Qwen2.5 teachers have 152064 rows, Qwen3 students
    151936; a takeover token above the student range crashes the student
    logprob gather). Enforced by post-generation truncation in the teacher
    server. ``0`` (default) disables the cap; same-family pairs need none.
``DTDD_TEACHER_VOCAB_ALLOWLIST=1``
    Enforce the cap with vLLM's ``allowed_token_ids`` sampler mask instead.
    Debugging only: a 151k-element allow-list per request corrupted GPU
    memory at a few hundred concurrent takeovers on both the flash-attn and
    Triton backends -- the sampler mask machinery is built for the short
    lists of structured decoding.
"""

import asyncio
import copy
import logging
import os
import random
import time
from typing import Any
from uuid import uuid4

import numpy as np
import ray

from verl.experimental.agent_loop.agent_loop import (
    AgentLoopOutput,
    AsyncLLMServerManager,
)
from verl.experimental.agent_loop.tool_agent_loop import (
    ToolAgentLoop,
    _to_token_id_list,
)
from verl.utils.profiler import simple_timer
from verl.utils.rollout_trace import rollout_trace_op

logger = logging.getLogger(__file__)
logger.setLevel(os.getenv("VERL_LOGGING_LEVEL", "WARN"))

TEACHER_SERVER_NAME = "dtdd_teacher_server"


class DTDDTeacherServerManager(AsyncLLMServerManager):
    """``AsyncLLMServerManager`` over the teacher pool, plus ``score``."""

    async def score(
        self, request_id: str, *, prompt_ids: list[int], num_tokens: int
    ):
        """Teacher logprobs of the last ``num_tokens`` of ``prompt_ids``.

        Routing is sticky: the same ``request_id`` that generates also scores,
        so a takeover lands on the teacher server that scored its trigger.

        Args:
            request_id: The episode's request id.
            prompt_ids: The full token sequence so far.
            num_tokens: How many trailing tokens to score.

        Returns:
            A ``TokenOutput`` whose ``log_probs`` has length ``num_tokens``.
        """
        server = self._choose_server(request_id)
        return await server.score.remote(
            request_id=request_id, prompt_ids=prompt_ids, num_tokens=num_tokens
        )


class DTDDToolAgentLoop(ToolAgentLoop):
    """``ToolAgentLoop`` with divergence-triggered teacher takeover."""

    _dtdd_class_initialized = False
    _teacher_manager: DTDDTeacherServerManager = None

    @classmethod
    def init_class(cls, config, tokenizer, processor, **kwargs) -> None:
        super().init_class(
            config=config, tokenizer=tokenizer, processor=processor, **kwargs
        )
        if cls._dtdd_class_initialized:
            return
        cls._dtdd_class_initialized = True

        cls.dtdd_cfg = config.get("dtdd", None)
        cls.full_config = config
        if cls.dtdd_cfg is not None and cls.dtdd_cfg.enable:
            assert config.actor_rollout_ref.rollout.calculate_log_probs, (
                "DTDD divergence trigger needs student rollout logprobs: "
                "set actor_rollout_ref.rollout.calculate_log_probs=True"
            )
            cls.dtdd_teacher_dp = (
                config.trainer.n_gpus_per_node
                * config.trainer.nnodes
                // config.dtdd.teacher.tensor_model_parallel_size
            )
            print(
                f"DTDD agent loop active: tau={cls.dtdd_cfg.tau} "
                f"epsilon_random={cls.dtdd_cfg.epsilon_random} "
                f"takeover_mode={cls.dtdd_cfg.takeover_mode} "
                f"dry_run={cls.dtdd_cfg.dry_run} "
                f"teacher_dp={cls.dtdd_teacher_dp}"
            )

    @classmethod
    def _get_teacher_manager(cls) -> DTDDTeacherServerManager:
        """Lazily look up the teacher actors ``DTDDRayPPOTrainer`` made."""
        if cls._teacher_manager is None:
            handles = [
                ray.get_actor(f"{TEACHER_SERVER_NAME}_{i}")
                for i in range(cls.dtdd_teacher_dp)
            ]
            cls._teacher_manager = DTDDTeacherServerManager(
                cls.full_config, handles
            )
        return cls._teacher_manager

    @rollout_trace_op
    async def run(
        self, sampling_params: dict[str, Any], **kwargs
    ) -> AgentLoopOutput:
        """Run one episode, possibly handing its tail to the teacher.

        Args:
            sampling_params: The student's vLLM sampling parameters.
            **kwargs: The stock agent-loop inputs (``raw_prompt``,
                ``tools_kwargs``, ``multi_modal_data``) plus the DTDD
                ``dtdd_validate`` flag injected by the trainer proxy.

        Returns:
            The stock ``AgentLoopOutput``; with DTDD active, ``extra_fields``
            also carries ``teacher_kl_mask`` and the ``dtdd_*`` telemetry.
        """
        # ---- DTDD episode setup ------------------------------------------
        cfg = self.dtdd_cfg
        is_validate = bool(kwargs.get("dtdd_validate", False))
        dtdd_active = bool(cfg is not None and cfg.enable and not is_validate)

        taken_over = False
        trigger_mode = None
        random_k = None
        switch_turn = -1
        dk_values: list[float] = []
        would_trigger_turn = -1  # dry-run: first turn that WOULD have triggered
        score_failures = 0
        score_ms_total = 0.0
        origin_mask: list[int] = []

        teacher_manager = None
        teacher_sampling_params = None
        if dtdd_active:
            teacher_manager = self._get_teacher_manager()
            trigger_mode = (
                "divergence"
                if random.random() >= float(cfg.epsilon_random)
                else "random"
            )
            if trigger_mode == "random":
                random_k = random.randint(
                    int(cfg.min_prefix_turns), int(cfg.random_turn_max)
                )
            teacher_sampling_params = {
                "temperature": float(cfg.teacher.temperature),
                "top_p": float(cfg.teacher.top_p),
                "repetition_penalty": 1.0,
                # Mirror the student's logprobs request: the stock loop only
                # appends to response_logprobs when they are present, so a
                # logprob-less teacher turn would shift rollout_log_probs.
                "logprobs": sampling_params.get("logprobs", False),
            }
            vocab_cap = int(os.environ.get("DTDD_TEACHER_VOCAB_CAP", "0"))
            use_allowlist = (
                os.environ.get("DTDD_TEACHER_VOCAB_ALLOWLIST", "0") == "1"
            )
            if vocab_cap > 0 and use_allowlist:
                teacher_sampling_params["allowed_token_ids"] = list(
                    range(vocab_cap)
                )

        # ---- Pinned copy of ToolAgentLoop.run ----------------------------
        messages = list(kwargs["raw_prompt"])
        image_data = copy.deepcopy(
            kwargs.get("multi_modal_data", {}).get("image", None)
        )
        metrics = {}
        request_id = uuid4().hex
        if self.processor is not None:
            raw_prompt = await self.loop.run_in_executor(
                None,
                lambda: self.processor.apply_chat_template(
                    messages,
                    tools=self.tool_schemas,
                    add_generation_prompt=True,
                    tokenize=False,
                    **self.apply_chat_template_kwargs,
                ),
            )
            model_inputs = self.processor(
                text=[raw_prompt], images=image_data, return_tensors="pt"
            )
            prompt_ids = model_inputs.pop("input_ids").squeeze(0).tolist()
        else:
            prompt_ids = await self.loop.run_in_executor(
                None,
                lambda: self.tokenizer.apply_chat_template(
                    messages,
                    tools=self.tool_schemas,
                    add_generation_prompt=True,
                    tokenize=True,
                    **self.apply_chat_template_kwargs,
                ),
            )
            prompt_ids = _to_token_id_list(prompt_ids)
        response_mask, response_logprobs = [], []
        tools_kwargs = kwargs.get("tools_kwargs", {})
        total_tool_calls = 0
        total_tool_success = 0

        user_turns, assistant_turns = 0, 0
        while True:
            # DTDD random trigger: checked BEFORE generating turn
            # (assistant_turns + 1).
            if (
                dtdd_active
                and not taken_over
                and trigger_mode == "random"
                and assistant_turns + 1 == random_k
                and not cfg.dry_run
            ):
                remaining_budget = self.response_length - len(response_mask)
                if remaining_budget >= int(cfg.min_takeover_budget):
                    taken_over = True
                    switch_turn = assistant_turns + 1
                else:
                    # Budget too small at random_k: skip takeover this episode.
                    trigger_mode = "random_skipped"

            mgr = teacher_manager if taken_over else self.server_manager
            params = teacher_sampling_params if taken_over else sampling_params
            with simple_timer("generate_sequences", metrics):
                output = await mgr.generate(
                    request_id=request_id,
                    prompt_ids=prompt_ids,
                    sampling_params=params,
                    image_data=image_data,
                )
            response_ids = output.token_ids
            prompt_ids += response_ids
            response_mask += [1] * len(response_ids)
            origin_mask += [0 if taken_over else 1] * len(response_ids)
            if output.log_probs:
                response_logprobs += output.log_probs
            assistant_turns += 1

            # DTDD divergence scoring on the freshly generated student turn.
            if (
                dtdd_active
                and not taken_over
                and trigger_mode == "divergence"
                and len(response_ids) > 0
            ):
                d_k = None
                try:
                    t0 = time.monotonic()
                    scored = await teacher_manager.score(
                        request_id,
                        prompt_ids=prompt_ids,
                        num_tokens=len(response_ids),
                    )
                    score_ms_total += (time.monotonic() - t0) * 1e3
                    student_lp = np.asarray(
                        output.log_probs[-len(response_ids):], dtype=np.float64
                    )
                    teacher_lp = np.asarray(scored.log_probs, dtype=np.float64)
                    assert len(student_lp) == len(teacher_lp)
                    # Same divergence as compute_stepwise_opd_weights.
                    d_k = float(np.mean(np.abs(student_lp - teacher_lp)))
                    dk_values.append(d_k)
                except Exception as exc:  # scoring must never kill the episode
                    score_failures += 1
                    logger.warning(
                        f"DTDD teacher scoring failed at turn "
                        f"{assistant_turns}: {exc}"
                    )

                if (
                    d_k is not None
                    and d_k > float(cfg.tau)
                    and assistant_turns >= int(cfg.min_prefix_turns)
                ):
                    budget_ok = (
                        self.response_length - len(response_mask)
                        >= int(cfg.min_takeover_budget)
                    )
                    if would_trigger_turn < 0:
                        would_trigger_turn = assistant_turns
                    if budget_ok and not cfg.dry_run:
                        taken_over = True
                        switch_turn = assistant_turns
                        if cfg.takeover_mode == "rewind":
                            # Discard the divergent turn: the teacher inherits
                            # h_{k-1} and regenerates turn k. prompt_ids still
                            # ends with the generation prompt after truncation
                            # (the chat template adds one to every tool/user
                            # message), so the teacher starts a well-formed
                            # assistant turn.
                            n = len(response_ids)
                            prompt_ids = prompt_ids[:-n]
                            response_mask = response_mask[:-n]
                            origin_mask = origin_mask[:-n]
                            if response_logprobs:
                                response_logprobs = response_logprobs[:-n]
                            continue
                        # "inherit": keep the divergent turn; the teacher
                        # continues from k+1.

            # reach max response length
            if len(response_mask) >= self.response_length:
                break

            # reach max assistant turns
            if (
                self.max_assistant_turns
                and assistant_turns >= self.max_assistant_turns
            ):
                break

            # reach max user turns
            if self.max_user_turns and user_turns >= self.max_user_turns:
                break

            # no tool calls
            _, tool_calls = await self.tool_parser.extract_tool_calls(
                response_ids
            )
            if not tool_calls:
                break

            # call tools
            tasks = []
            for tool_call in tool_calls[: self.max_parallel_calls]:
                tasks.append(self._call_tool(tool_call, tools_kwargs))
            with simple_timer("tool_calls", metrics):
                tool_results = await asyncio.gather(*tasks)
            total_tool_calls += len(tool_results)
            if any(isinstance(item, Exception) for item in tool_results):
                break

            tool_responses = []
            for tool_response, error_flag in tool_results:
                if not error_flag:
                    total_tool_success += 1
                tool_responses.append(tool_response)

            # Extract messages and update multi_modal_data
            tool_messages = []
            new_images_this_turn = []
            for tool_response in tool_responses:
                if tool_response.image or tool_response.video:
                    content = []
                    if tool_response.image:
                        content.append({"type": "image"})
                    if tool_response.video:
                        content.append({"type": "video"})
                    if tool_response.text:
                        content.append(
                            {"type": "text", "text": tool_response.text}
                        )
                    message = {"role": "tool", "content": content}
                else:
                    message = {
                        "role": "tool", "content": tool_response.text or ""
                    }

                tool_messages.append(message)

                if tool_response.image:
                    if image_data is None:
                        image_data = []
                    elif not isinstance(image_data, list):
                        image_data = [image_data]

                    if isinstance(tool_response.image, list):
                        image_data.extend(tool_response.image)
                        new_images_this_turn.extend(tool_response.image)
                    else:
                        image_data.append(tool_response.image)
                        new_images_this_turn.append(tool_response.image)

                if tool_response.video:
                    logger.warning(
                        "Multimedia type 'video' is not currently supported. "
                        "Only 'image' is supported."
                    )
                    raise NotImplementedError(
                        "Multimedia type 'video' is not currently supported. "
                        "Only 'image' is supported."
                    )

            # append tool_response_ids
            if self.processor is not None:
                raw_tool_response = await self.loop.run_in_executor(
                    None,
                    lambda messages=tool_messages: (
                        self.processor.apply_chat_template(
                            messages,
                            add_generation_prompt=True,
                            tokenize=False,
                            **self.apply_chat_template_kwargs,
                        )
                    ),
                )
                current_images = (
                    new_images_this_turn if new_images_this_turn else None
                )
                model_inputs = self.processor(
                    text=[raw_tool_response],
                    images=current_images,
                    return_tensors="pt",
                )
                tool_response_ids = (
                    model_inputs.pop("input_ids").squeeze(0).tolist()
                )
            else:
                tool_response_ids = await self.loop.run_in_executor(
                    None,
                    lambda messages=tool_messages: (
                        self.tokenizer.apply_chat_template(
                            messages,
                            add_generation_prompt=True,
                            tokenize=True,
                            **self.apply_chat_template_kwargs,
                        )
                    ),
                )
                tool_response_ids = _to_token_id_list(tool_response_ids)
            tool_response_ids = tool_response_ids[len(self.system_prompt):]

            # NOTE: last turn should not be user turn, or the EOS token reward
            # can't be propagated to previous token in GAE.
            if (
                len(response_mask) + len(tool_response_ids)
                >= self.response_length
            ):
                break

            prompt_ids += tool_response_ids
            response_mask += [0] * len(tool_response_ids)
            origin_mask += [0] * len(tool_response_ids)
            if response_logprobs:
                response_logprobs += [0.0] * len(tool_response_ids)
            user_turns += 1

        response_ids = prompt_ids[-len(response_mask):]
        prompt_ids = prompt_ids[: len(prompt_ids) - len(response_mask)]

        multi_modal_data = (
            {"image": image_data} if image_data is not None else {}
        )

        output = AgentLoopOutput(
            prompt_ids=prompt_ids,
            response_ids=response_ids[: self.response_length],
            response_mask=response_mask[: self.response_length],
            multi_modal_data=multi_modal_data,
            response_logprobs=(
                response_logprobs[: self.response_length]
                if response_logprobs
                else None
            ),
            num_turns=user_turns + assistant_turns + 1,
            metrics=metrics,
        )

        # ---- DTDD origin mask + telemetry ---------------------------------
        if dtdd_active:
            # Emit on EVERY dtdd-active path (dry-run, no-trigger, scoring
            # failure): _postprocess includes teacher_kl_mask only if ALL
            # samples in the batch emit it.
            emitted_origin = origin_mask[: self.response_length]
            assert len(emitted_origin) == len(output.response_mask), (
                f"DTDD origin mask length {len(emitted_origin)} != "
                f"response_mask length {len(output.response_mask)}"
            )
            output.extra_fields["teacher_kl_mask"] = emitted_origin

        extra_payload = {
            "num_tool_calls": total_tool_calls,
            "num_tool_success": total_tool_success,
            "num_turns": output.num_turns,
        }
        if dtdd_active:
            teacher_tokens = int(
                sum(
                    1
                    for o, r in zip(origin_mask, response_mask)
                    if o == 0 and r == 1
                )
            )
            student_tokens = int(sum(origin_mask))
            extra_payload.update(
                {
                    "dtdd_triggered": int(taken_over),
                    "dtdd_trigger_mode": trigger_mode,
                    "dtdd_switch_turn": int(switch_turn),
                    "dtdd_random_k": (
                        int(random_k) if random_k is not None else -1
                    ),
                    "dtdd_dk_values": [round(v, 6) for v in dk_values],
                    "dtdd_would_trigger_turn": int(would_trigger_turn),
                    "dtdd_teacher_tokens": teacher_tokens,
                    "dtdd_empty_prefix": int(
                        taken_over and student_tokens == 0
                    ),
                    "dtdd_score_ms_total": round(score_ms_total, 1),
                    "dtdd_score_failures": int(score_failures),
                }
            )
        output.extra_fields["extra_info"] = extra_payload
        return output
