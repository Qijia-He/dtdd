"""Shared core of the agentic DTDD workflows (ALFWorld, WebShop).

This is the agentic counterpart of the math-lane recipe in ``recipe_dtdd/``.
It forks the plain on-policy distillation (OPD) workflows that ship with TCOD
and adds a per-turn, divergence-triggered teacher takeover. The turn loop is
identical across environments and lives here; each environment supplies its
own prompt construction, action execution and episode bookkeeping by
overriding the hooks listed at the bottom of this docstring.

How OPD trains here
-------------------
The student rolls out the whole multi-turn episode. The teacher scores the
student's action tokens, and the ``multi_turn_opd`` advantage trains on the
per-token reverse KL, ``teacher_logprobs - student_logprobs``, over each
student turn.

What DTDD adds
--------------
At every turn the student first samples its action. The teacher scores those
tokens, giving the per-turn divergence

    turn_divergence = mean_t |logp_student(t) - logp_teacher(t)|

over the turn's action tokens -- the same mean-|logp gap| statistic the math
lane computes per window. If ``turn_divergence > tau`` (and the turn index is
at least ``min_prefix_turns``, and this is not an evaluation episode), the
TEACHER generates that turn's action instead. The teacher's action is executed
in the environment, so the trajectory sees a real observation, and the
recorded experience for that turn is filled so that the student trains to
imitate the teacher:

    recorded.logprobs         = student logp on the TEACHER's tokens
                                (this becomes ``old_log_probs``)
    recorded.teacher_logprobs = teacher logp on the TEACHER's tokens

The existing advantage, ``kl_coef * (teacher_logprobs - old_log_probs)``, is
therefore an imitation signal on a teacher-written turn and is identical to
plain OPD on a non-triggered (student) turn, where

    recorded.logprobs         = student sampling logp on the student's tokens
    recorded.teacher_logprobs = teacher logp on the student's tokens

Both turn types emit the same experience schema (tokens, logprobs,
teacher_logprobs, action_mask, prompt_length, reward, eid), so no trainer or
advantage changes are needed. Evaluation is student-only (the trigger is gated
on ``not self.is_eval``), so the OPD-vs-DTDD comparison stays fair.

Token alignment
---------------
As in OPD, one model scores tokens generated by the other, which assumes the
student and teacher share a tokenizer (in the paper's arms both are Qwen2.5
family). For a teacher turn the student scores the teacher's tokens; the
response boundary is taken from the GENERATING model's ``prompt_length``
(``response_start = prompt_length - 1``), mirroring OPD's
teacher-scores-student slicing exactly.

Tensor shapes
-------------
All per-turn log-probability tensors are 1-D over the turn's response tokens:

    R = number of response tokens in the turn

    student_logprobs:  [R]   logp of each response token under the student
    teacher_logprobs:  [R]   logp of each response token under the teacher

Hooks a subclass implements
---------------------------
``_reset_env``            start an episode; return the first observation
``_format_actions``       render the environment's action menu for the prompt
``_build_user_content``   render this turn's user message
``_execute_action``       run the recorded action; return the step result
``_finalize_episode``     record env_done / env_rounds / the episode reward
``_episode_metrics``      add environment-specific metrics to the last turn
``_rescore_teacher_turn`` optional: guard the takeover re-scoring

Subclasses also implement ``run_async``, because episode lifetimes differ:
ALFWorld builds and closes one environment per episode, while WebShop resets a
persistent environment by session id and rolls out ``repeat_times`` episodes.
"""

from __future__ import annotations

from dataclasses import asdict
from typing import Any, Dict, List, Optional, Tuple

from torch import Tensor

from trinity.common.experience import Experience
from trinity.common.models.model import ModelWrapper
from trinity.common.workflows import Task, Workflow

# Defaults for ``task.workflow_args``. ``max_env_steps`` has no shared default;
# each environment sets ``DEFAULT_MAX_ENV_STEPS`` on its subclass.
DEFAULT_TAU = 0.7
DEFAULT_MIN_PREFIX_TURNS = 1
DEFAULT_TEMPERATURE = 1.0


class DTDDAgenticWorkflow(Workflow):
    """Divergence-triggered teacher takeover over a multi-turn environment.

    Use ``advantage_fn: multi_turn_opd`` (``MultiTurnOpdAdvantage``), the same
    as OPD. It returns one ``Experience`` per turn and computes
    ``advantages = kl_coef * (teacher_logprobs - student_logprobs)``.

    Recognized ``task.workflow_args``:

        tau (float): divergence threshold; the teacher takes over the turn
            when ``turn_divergence > tau``. Default 0.7.
        min_prefix_turns (int): earliest 1-based turn index eligible for a
            takeover. Default 1 (every turn is eligible).
        temperature (float): temperature for the scoring (log-prob) calls.
            Default 1.0.
        max_env_steps (int): maximum episode length in environment steps.
            Defaults to the subclass's ``DEFAULT_MAX_ENV_STEPS``.
    """

    is_async: bool = True
    can_reset: bool = True

    # Subclass configuration.
    WORKFLOW_NAME: str = "DTDD_workflow"
    DEFAULT_MAX_ENV_STEPS: int = 30

    # Class-level default so that an environment whose ``reset`` does not set
    # ``repeat_times`` (ALFWorld, which rolls out one episode per task) still
    # has the attribute.
    repeat_times: int = 1

    def __init__(
        self,
        *,
        task: Task,
        model: ModelWrapper,
        auxiliary_models: Optional[List[ModelWrapper]] = None,
    ) -> None:
        super().__init__(
            task=task,
            model=model,
            auxiliary_models=auxiliary_models,
        )
        self.reset(task)

        assert (
            self.auxiliary_model_wrappers is not None
            and len(self.auxiliary_model_wrappers) >= 1
        ), "DTDD requires at least one auxiliary model to act as the teacher."
        self.teacher_model: ModelWrapper = self.auxiliary_model_wrappers[0]

        workflow_args = task.workflow_args
        self.temperature: float = float(
            workflow_args.get("temperature", DEFAULT_TEMPERATURE)
        )
        self.max_env_steps: int = int(
            workflow_args.get("max_env_steps", self.DEFAULT_MAX_ENV_STEPS)
        )
        self.tau: float = float(workflow_args.get("tau", DEFAULT_TAU))
        self.min_prefix_turns: int = int(
            workflow_args.get("min_prefix_turns", DEFAULT_MIN_PREFIX_TURNS)
        )

        # Episode state, populated by ``_run_episode``.
        self._env_done: bool = False
        self._env_rounds: int = 0
        self._final_reward: float = 0.0
        self.run_id_base: int = 0

    # ------------------------------------------------------------ plumbing --
    def reset(self, task: Task) -> None:
        """Reset the workflow with a new task."""
        self.task = task
        self.format_args = task.format_args
        self.raw_task = task.raw_task
        self.task_desc: str = task.task_desc or "0"
        self.is_eval: bool = task.is_eval

    def set_repeat_times(self, repeat_times: int, run_id_base: int) -> None:
        """Record the rollout count and the base run id used for their eids."""
        self.repeat_times = repeat_times
        self.task.rollout_args.n = repeat_times
        self.run_id_base = run_id_base

    def compute_reward(self, response: Experience) -> float:
        """Return the episode-level reward, shared by all of its turns."""
        del response  # The reward is per-episode, not per-turn.
        return self._final_reward

    @property
    def rollout_args(self) -> Dict[str, Any]:
        """The task's generation config as a plain dict of kwargs."""
        return asdict(self.task.rollout_args)

    def format_messages(self) -> List[Dict[str, str]]:
        """Return the initial chat messages; episodes start with none."""
        return []

    @staticmethod
    def _compute_turn_divergence(
        student_logprobs: Tensor,
        teacher_logprobs: Tensor,
    ) -> float:
        """Compute the per-turn divergence between student and teacher.

        This is ``mean_t |logp_student(t) - logp_teacher(t)|`` over the turn's
        response tokens -- the same statistic the math lane uses per window.

        Args:
            student_logprobs: [R] log-probs of the response tokens under the
                student.
            teacher_logprobs: [R] log-probs of the same tokens under the
                teacher.

        Returns:
            The mean absolute log-prob gap, or 0.0 for an empty turn.
        """
        if len(student_logprobs) == 0:
            return 0.0
        return float((student_logprobs - teacher_logprobs).abs().mean().item())

    # --------------------------------------------------------------- hooks --
    def _extract_task_description(self, observation: str) -> str:
        """Pull the task statement out of an episode's first observation."""
        raise NotImplementedError

    def _format_observation(self, observation: str) -> str:
        """Render a raw observation for the prompt."""
        raise NotImplementedError

    def _reset_env(self, env: Any) -> str:
        """Start an episode and return its first observation.

        Implementations also reset ``_env_done`` / ``_env_rounds`` and any
        environment-specific episode state.

        Args:
            env: The environment for this episode.

        Returns:
            The raw first observation.
        """
        raise NotImplementedError

    def _format_actions(self, env: Any) -> str:
        """Return the environment's currently available actions, rendered."""
        raise NotImplementedError

    def _build_user_content(
        self,
        *,
        task_description: str,
        turn_index: int,
        history: List[str],
        formatted_observation: str,
        formatted_actions: str,
    ) -> str:
        """Render this turn's user message from the environment's templates."""
        raise NotImplementedError

    def _execute_action(
        self,
        env: Any,
        *,
        response_text: str,
        formatted_observation: str,
        turn_index: int,
        history: List[str],
    ) -> Tuple[str, float, bool]:
        """Execute the recorded turn's action and advance the environment.

        Implementations append this turn's entry to ``history``.

        Args:
            env: The environment for this episode.
            response_text: The recorded turn's raw text.
            formatted_observation: The observation the action was chosen from.
            turn_index: 0-based index of this turn.
            history: The episode's action history, appended to in place.

        Returns:
            The next observation, this step's reward, and whether the episode
            is done.
        """
        raise NotImplementedError

    def _finalize_episode(
        self, *, turn_index: Optional[int], done: bool, reward: float
    ) -> None:
        """Record ``_env_done`` / ``_env_rounds`` / ``_final_reward``.

        Args:
            turn_index: 0-based index of the final turn, or None when the
                episode ran out of steps without finishing.
            done: Whether the environment reported the episode as done.
            reward: The last step's reward.
        """
        raise NotImplementedError

    def _episode_metrics(self) -> Dict[str, float]:
        """Return environment-specific metrics for the last turn.

        The shared metrics (``env_rounds``, ``env_done``, ``kl_divergence``
        and the DTDD telemetry) are added by ``_run_episode``.
        """
        return {}

    async def _rescore_teacher_turn(
        self, teacher_response: Experience, teacher_response_length: int
    ) -> Tuple[Optional[Tensor], Optional[Tensor], int]:
        """Score a teacher-generated turn under both models.

        This base implementation lets any failure propagate, which is the
        behaviour the ALFWorld arms were run with. WebShop overrides it to
        skip over-long turns and to fall back to the student's turn on error;
        see that subclass for why.

        Args:
            teacher_response: The teacher's generated turn.
            teacher_response_length: Its response length in tokens.

        Returns:
            The student's log-probs on the teacher's tokens, the teacher's
            log-probs on its own tokens, and the response length -- or
            ``(None, None, 0)`` when the turn must fall back to the student.
        """
        teacher_response_start = teacher_response.prompt_length - 1

        # Student log-probs on the teacher's tokens: this becomes
        # ``old_log_probs`` for the imitation update.
        student_on_teacher_full = await self.model.logprobs_async(
            tokens=teacher_response.tokens.tolist(),
            temperature=self.temperature,
        )
        # Teacher log-probs on its own tokens, scored cleanly with the same
        # convention as OPD: the imitation target.
        teacher_on_teacher_full = await self.teacher_model.logprobs_async(
            tokens=teacher_response.tokens.tolist(),
            temperature=self.temperature,
        )
        return (
            student_on_teacher_full[teacher_response_start:],
            teacher_on_teacher_full[teacher_response_start:],
            teacher_response_length,
        )

    # --------------------------------------------------------- the DTDD loop --
    async def _run_episode(  # noqa: C901
        self, env: Any, run_id: int
    ) -> List[Experience]:
        """Roll out one episode with divergence-triggered teacher takeover.

        Args:
            env: The environment for this episode.
            run_id: The run id stamped on every experience's eid.

        Returns:
            One ``Experience`` per executed turn, in order. Every experience
            carries ``logprobs`` and ``teacher_logprobs`` in the schema that
            the ``multi_turn_opd`` advantage expects; the last one also
            carries the episode-level metrics.
        """
        observation = self._reset_env(env)
        task_description = self._extract_task_description(observation)
        history: List[str] = []
        memory = self.format_messages()
        turn_responses: List[Experience] = []

        generation_kwargs: Dict[str, Any] = {**self.rollout_args, "n": 1}
        if generation_kwargs.get("logprobs") is None:
            generation_kwargs["logprobs"] = 0

        per_turn_kl_sums: List[float] = []
        turn_divergences: List[float] = []
        takeover_count = 0

        for turn_index in range(self.max_env_steps):
            formatted_observation = self._format_observation(observation)
            formatted_actions = self._format_actions(env)
            user_content = self._build_user_content(
                task_description=task_description,
                turn_index=turn_index,
                history=history,
                formatted_observation=formatted_observation,
                formatted_actions=formatted_actions,
            )

            # The assistant message is appended only after the student-vs-
            # teacher decision below, so the chat history matches the action
            # that was actually executed in the environment.
            memory = memory + [{"role": "user", "content": user_content}]

            # Step 1: the student samples this turn, exactly as in OPD.
            student_responses = await self.model.chat_async(
                memory, **generation_kwargs
            )
            student_response = student_responses[0]
            if student_response.logprobs is None:
                raise RuntimeError(
                    f"{self.WORKFLOW_NAME} requires the student model to "
                    "return logprobs. Set rollout_args.logprobs (e.g. 0) in "
                    "the task config."
                )

            # Step 2: the teacher scores the student's turn. This is both the
            # OPD signal for a student turn and the DTDD trigger statistic.
            teacher_logprobs_full = await self.teacher_model.logprobs_async(
                tokens=student_response.tokens.tolist(),
                temperature=self.temperature,
            )
            student_response_start = student_response.prompt_length - 1
            teacher_logprobs = teacher_logprobs_full[student_response_start:]
            student_logprobs = student_response.logprobs
            assert len(teacher_logprobs) == len(student_logprobs), (
                f"[DTDD] student-turn length mismatch: "
                f"teacher={len(teacher_logprobs)}, "
                f"student={len(student_logprobs)}, "
                f"tokens={len(student_response.tokens)}, "
                f"prompt_length={student_response.prompt_length}"
            )

            turn_divergence = self._compute_turn_divergence(
                student_logprobs, teacher_logprobs
            )
            turn_divergences.append(turn_divergence)

            # Evaluation episodes are always student-only, so that OPD and
            # DTDD are compared on the same footing.
            should_take_over = (
                not self.is_eval
                and turn_divergence > self.tau
                and (turn_index + 1) >= self.min_prefix_turns
                and len(student_logprobs) > 0
            )

            recorded_response = student_response
            is_teacher_turn = False

            # Step 3 (on trigger): the teacher generates the turn instead.
            if should_take_over:
                teacher_responses = await self.teacher_model.chat_async(
                    memory, **generation_kwargs
                )
                teacher_response = teacher_responses[0]
                teacher_response_length = (
                    len(teacher_response.tokens)
                    - teacher_response.prompt_length
                )

                student_on_teacher: Optional[Tensor] = None
                teacher_on_teacher: Optional[Tensor] = None
                rescored_length = 0
                if teacher_response_length > 0:
                    (
                        student_on_teacher,
                        teacher_on_teacher,
                        rescored_length,
                    ) = await self._rescore_teacher_turn(
                        teacher_response, teacher_response_length
                    )

                if rescored_length > 0:
                    assert (
                        len(student_on_teacher)
                        == len(teacher_on_teacher)
                        == rescored_length
                    ), (
                        f"[DTDD] teacher-turn length mismatch: "
                        f"student_on_teacher={len(student_on_teacher)}, "
                        f"teacher_on_teacher={len(teacher_on_teacher)}, "
                        f"response_length={rescored_length}, "
                        f"tokens={len(teacher_response.tokens)}, "
                        f"prompt_length={teacher_response.prompt_length}"
                    )

                    teacher_response.logprobs = student_on_teacher
                    teacher_response.teacher_logprobs = teacher_on_teacher
                    recorded_response = teacher_response
                    is_teacher_turn = True
                    takeover_count += 1
                # An empty or skipped teacher turn falls back to the student.

            if not is_teacher_turn:
                # A non-triggered turn is identical to OPD.
                student_response.teacher_logprobs = teacher_logprobs

            # Append the assistant message for the action that will execute.
            response_text = recorded_response.response_text or ""
            memory.append({"role": "assistant", "content": response_text})

            if recorded_response.logprobs is None:
                raise RuntimeError(
                    f"{self.WORKFLOW_NAME} requires logprobs on the recorded "
                    "turn."
                )
            turn_responses.append(recorded_response)

            # Per-turn KL, ``sum_t (student_logp - teacher_logp)``, over the
            # recorded turn.
            kl_sum = (
                recorded_response.logprobs - recorded_response.teacher_logprobs
            ).sum().item()
            per_turn_kl_sums.append(kl_sum)

            if recorded_response.metrics is None:
                recorded_response.metrics = {}
            # Metric keys are the on-disk telemetry schema read by the
            # harvest and plotting tools; they are not renamed.
            recorded_response.metrics["if_teacher"] = float(is_teacher_turn)
            recorded_response.metrics["d_k"] = turn_divergence

            observation, reward, done = self._execute_action(
                env,
                response_text=response_text,
                formatted_observation=formatted_observation,
                turn_index=turn_index,
                history=history,
            )
            if done:
                self._finalize_episode(
                    turn_index=turn_index, done=True, reward=reward
                )
                break
        else:
            # Exhausted ``max_env_steps`` without finishing.
            self._finalize_episode(turn_index=None, done=False, reward=0.0)

        # Finalize: episode reward and eids. ``teacher_logprobs`` is already
        # set on every turn above.
        for step_index, response in enumerate(turn_responses):
            if response.metrics is None:
                response.metrics = {}
            response.reward = self.compute_reward(response)
            response.eid.run = run_id
            response.eid.step = step_index

        trajectory_kl_divergence = sum(per_turn_kl_sums)
        num_turns = len(turn_responses)
        takeover_rate = (
            (takeover_count / num_turns) if num_turns > 0 else 0.0
        )

        if turn_responses:
            last_response = turn_responses[-1]
            if last_response.metrics is None:
                last_response.metrics = {}
            last_response.metrics["env_rounds"] = self._env_rounds
            last_response.metrics["env_done"] = 1.0 if self._env_done else 0.0
            last_response.metrics["kl_divergence"] = trajectory_kl_divergence
            last_response.metrics.update(self._episode_metrics())
            # DTDD telemetry.
            last_response.metrics["takeover_rate"] = takeover_rate
            last_response.metrics["teacher_env_rounds"] = takeover_count
            last_response.metrics["student_env_rounds"] = (
                num_turns - takeover_count
            )
            last_response.metrics["mean_d_k"] = (
                sum(turn_divergences) / len(turn_divergences)
                if turn_divergences
                else 0.0
            )

        return turn_responses
